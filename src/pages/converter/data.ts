export type GaugePoint = {
    readonly name: string;
    readonly inches: number;
};

export const fractionalInches: readonly GaugePoint[] = Array.from({ length: 63 }, (_, index) => {
    const numerator = index + 1;
    return { name: `${numerator}/64`, inches: numerator / 64 };
}).reverse();

