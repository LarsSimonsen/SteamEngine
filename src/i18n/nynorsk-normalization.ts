const normalizeText = (value: string): string => replacements.reduce(
    (current, [pattern, replacement]) => current.replace(pattern, replacement),
    value,
);

export const normalizeNynorsk = <T>(value: T): T => {
    if (typeof value === "string") return normalizeText(value) as T;
    if (Array.isArray(value)) return value.map((item) => normalizeNynorsk(item)) as T;
    if (value !== null && typeof value === "object") {
        return Object.fromEntries(Object.entries(value).map(([key, item]) => [
            key,
            normalizeNynorsk(item),
        ])) as T;
    }
    return value;
};
