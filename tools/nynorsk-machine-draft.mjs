export const toNynorskText = (value) => replacements.reduce(
    (current, [pattern, replacement]) => current.replace(pattern, replacement),
    value,
);

export const toNynorskValue = (value) => {
    if (typeof value === "string") return toNynorskText(value);
    if (value === undefined || value === null) return value;
    if (Array.isArray(value)) return value.map(toNynorskValue);
    if (value !== null && typeof value === "object") {
        return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, toNynorskValue(item)]));
    }
    throw new Error("Nynorsk materialization received an unsupported value");
};
